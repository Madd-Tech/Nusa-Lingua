-- =====================================================================
-- Nusa Lingua — moderasi inti (Fase A, lihat docs/rancangan-moderator.md)
--
--   P1  Alur moderasi: alasan penolakan, catatan, edit sebelum setuju,
--       cek duplikat, reviewed_at, XP kontributor, batas 20 usulan
--       menunggu per user. Semua keputusan lewat RPC review_submission
--       (reviewed_by diisi dari auth.uid(), tidak bisa dipalsukan client).
--   P2  Moderator per bahasa: tabel moderator_languages, helper
--       moderated_language_ids()/can_moderate(), RPC admin
--       set_moderator_languages.
--   +   moderation_log: catatan semua tindakan moderasi.
--
-- Jalankan SEKALI setelah 0001–0004 (dan seed). Moderator yang sudah ada
-- otomatis ditugaskan ke semua bahasa; admin merapikan di /moderasi/tim.
--
-- Kode error khusus (dibaca UI lewat error.code):
--   NL409  usulan sudah ditinjau moderator lain
--   NL422  validasi (alasan kosong, duplikat, panjang teks, dsb.)
--   NL429  batas usulan menunggu tercapai
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- Enum
-- ---------------------------------------------------------------------
create type public.reject_reason as enum (
  'duplikat', 'ejaan', 'arti_keliru', 'bukan_bahasa_ini', 'tidak_pantas', 'audio_buruk', 'lainnya'
);

-- Daftar lengkap untuk semua fase, supaya fase berikutnya tidak perlu
-- `alter type ... add value` (tidak bisa dipakai di transaksi yang sama).
create type public.moderation_action as enum (
  'submission_approved', 'submission_rejected',
  'vocab_updated', 'vocab_hidden', 'vocab_restored',
  'article_created', 'article_updated', 'article_status_changed', 'article_deleted',
  'report_resolved', 'report_dismissed',
  'moderator_assigned', 'moderator_removed'
);

-- ---------------------------------------------------------------------
-- Tabel
-- ---------------------------------------------------------------------
create table public.moderator_languages (
  user_id uuid not null references public.profiles (id) on delete cascade,
  language_id bigint not null references public.languages (id) on delete cascade,
  assigned_by uuid references public.profiles (id) on delete set null,
  assigned_at timestamptz not null default now(),
  primary key (user_id, language_id)
);
create index moderator_languages_language_idx on public.moderator_languages (language_id);

create table public.moderation_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles (id) on delete set null,
  action public.moderation_action not null,
  language_id bigint references public.languages (id) on delete set null,
  target_type text not null check (target_type in ('submission', 'vocabulary', 'article', 'report', 'moderator')),
  target_id text not null,
  detail jsonb,
  created_at timestamptz not null default now()
);
create index moderation_log_language_idx on public.moderation_log (language_id, created_at desc);
create index moderation_log_actor_idx on public.moderation_log (actor_id, created_at desc);

alter table public.vocab_submissions
  add column reject_reason public.reject_reason,
  add column review_note text check (char_length(review_note) <= 500),
  add column reviewed_at timestamptz,
  -- {"word": "...", "meaning_id": "..."} sebelum diedit moderator; NULL bila tidak diedit.
  add column original jsonb,
  -- Entri kamus hasil persetujuan.
  add column vocabulary_id bigint references public.vocabularies (id) on delete set null;

-- NOT VALID: usulan lama yang ditolak tanpa alasan tidak ikut dicek.
alter table public.vocab_submissions
  add constraint submissions_rejected_has_reason
  check (status <> 'rejected' or reject_reason is not null) not valid;

create index submissions_reviewed_idx on public.vocab_submissions (reviewed_by, reviewed_at desc);

alter table public.vocabularies
  add column contributed_by uuid references public.profiles (id) on delete set null;

create index vocab_lang_word_lower_idx on public.vocabularies (language_id, lower(word));
create index vocab_contributed_by_idx on public.vocabularies (contributed_by);

-- ---------------------------------------------------------------------
-- Backfill
-- ---------------------------------------------------------------------

-- Moderator lama → semua bahasa (agar tidak tiba-tiba kehilangan akses).
insert into public.moderator_languages (user_id, language_id)
select p.id, l.id
from public.profiles p
cross join public.languages l
where p.role = 'moderator'
on conflict do nothing;

-- Kata hasil kontribusi sebelum migrasi ini: tandai sumbernya & tautkan ke usulannya.
update public.vocabularies
   set source = 'kontribusi'
 where category = 'kontribusi' and source is null;

update public.vocab_submissions s
   set vocabulary_id = v.id
  from public.vocabularies v
 where s.status = 'approved'
   and s.vocabulary_id is null
   and v.language_id = s.language_id
   and v.word = s.word
   and v.meaning_id = s.meaning_id
   and v.category = 'kontribusi';

update public.vocabularies v
   set contributed_by = s.user_id
  from public.vocab_submissions s
 where s.vocabulary_id = v.id
   and v.contributed_by is null;

-- ---------------------------------------------------------------------
-- Helper
-- ---------------------------------------------------------------------

-- true jika user saat ini admin.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

-- Bahasa yang boleh dimoderasi user saat ini. Admin = semua bahasa.
-- Di policy pakai `language_id in (select public.moderated_language_ids())`
-- agar dievaluasi sekali per query, bukan per baris.
create or replace function public.moderated_language_ids()
returns setof bigint
language sql
stable
security definer
set search_path = ''
as $$
  select l.id from public.languages l where public.is_admin()
  union
  select ml.language_id
  from public.moderator_languages ml
  join public.profiles p on p.id = ml.user_id and p.role = 'moderator'
  where ml.user_id = (select auth.uid());
$$;

-- Untuk RPC/trigger. Bahasa NULL (konten umum) = khusus admin.
create or replace function public.can_moderate(p_language_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when p_language_id is null then public.is_admin()
    else exists (select 1 from public.moderated_language_ids() as m (id) where m.id = p_language_id)
  end;
$$;

-- Catat tindakan moderasi (hanya dipanggil dari RPC/trigger).
create or replace function public.log_moderation(
  p_action public.moderation_action,
  p_language_id bigint,
  p_target_type text,
  p_target_id text,
  p_detail jsonb default null
)
returns void
language sql
security definer
set search_path = ''
as $$
  insert into public.moderation_log (actor_id, action, language_id, target_type, target_id, detail)
  values ((select auth.uid()), p_action, p_language_id, p_target_type, p_target_id, p_detail);
$$;

-- ---------------------------------------------------------------------
-- Trigger: batas usulan menunggu per user
-- ---------------------------------------------------------------------
create or replace function public.limit_pending_submissions()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (
    select count(*) from public.vocab_submissions
    where user_id = new.user_id and status = 'pending'
  ) >= 20 then
    raise exception 'Masih ada 20 usulanmu yang menunggu ditinjau. Tunggu sebagian ditinjau dulu, ya.'
      using errcode = 'NL429';
  end if;
  return new;
end;
$$;

create trigger vocab_submission_limit
  before insert on public.vocab_submissions
  for each row execute function public.limit_pending_submissions();

-- Persetujuan kini lewat review_submission (edit, duplikat, XP, log dalam satu transaksi).
drop trigger if exists vocab_submission_reviewed on public.vocab_submissions;
drop function if exists public.on_submission_reviewed();

-- ---------------------------------------------------------------------
-- RPC: review_submission
-- Setujui/tolak satu usulan. p_edits (opsional, hanya untuk 'approved'):
--   {"word", "meaning_id", "speech_level", "example_sentence", "example_meaning"}
-- Mengembalikan {"status", "vocabulary_id", "xp_awarded"}.
-- ---------------------------------------------------------------------
create or replace function public.review_submission(
  p_id bigint,
  p_decision public.submission_status,
  p_reject_reason public.reject_reason default null,
  p_note text default null,
  p_edits jsonb default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_xp constant integer := 15;
  s public.vocab_submissions%rowtype;
  v_note text := nullif(btrim(coalesce(p_note, '')), '');
  v_edits jsonb := coalesce(p_edits, '{}'::jsonb);
  v_word text;
  v_meaning text;
  v_speech_level text;
  v_example text;
  v_example_meaning text;
  v_edited boolean;
  v_vocab_id bigint;
begin
  if v_user is null then
    raise exception 'Harus login untuk meninjau usulan' using errcode = '28000';
  end if;

  select * into s from public.vocab_submissions where id = p_id for update;
  if not found then
    raise exception 'Usulan % tidak ditemukan', p_id using errcode = 'P0002';
  end if;

  if not public.can_moderate(s.language_id) then
    raise exception 'Kamu tidak memoderasi bahasa ini' using errcode = '42501';
  end if;
  if s.user_id = v_user then
    raise exception 'Usulanmu sendiri harus ditinjau moderator lain' using errcode = '42501';
  end if;
  if s.status <> 'pending' then
    raise exception 'Usulan ini sudah ditinjau moderator lain' using errcode = 'NL409';
  end if;
  if char_length(v_note) > 500 then
    raise exception 'Catatan maksimal 500 karakter' using errcode = 'NL422';
  end if;

  if p_decision = 'rejected' then
    if p_reject_reason is null then
      raise exception 'Pilih alasan penolakan' using errcode = 'NL422';
    end if;

    update public.vocab_submissions
       set status = 'rejected',
           reject_reason = p_reject_reason,
           review_note = v_note,
           reviewed_by = v_user,
           reviewed_at = now()
     where id = s.id;

    perform public.log_moderation(
      'submission_rejected', s.language_id, 'submission', s.id::text,
      jsonb_build_object('word', s.word, 'reason', p_reject_reason, 'note', v_note)
    );
    return jsonb_build_object('status', 'rejected');
  end if;

  if p_decision is distinct from 'approved' then
    raise exception 'Keputusan harus approved atau rejected' using errcode = 'NL422';
  end if;

  v_word := coalesce(nullif(btrim(v_edits ->> 'word'), ''), s.word);
  v_meaning := coalesce(nullif(btrim(v_edits ->> 'meaning_id'), ''), s.meaning_id);
  v_speech_level := nullif(btrim(v_edits ->> 'speech_level'), '');
  v_example := nullif(btrim(v_edits ->> 'example_sentence'), '');
  v_example_meaning := nullif(btrim(v_edits ->> 'example_meaning'), '');

  if char_length(v_word) > 80 or char_length(v_meaning) > 200 then
    raise exception 'Kata maksimal 80 karakter dan arti maksimal 200 karakter' using errcode = 'NL422';
  end if;
  if char_length(v_speech_level) > 40 or char_length(v_example) > 300 or char_length(v_example_meaning) > 300 then
    raise exception 'Tingkat tutur maksimal 40 karakter, contoh kalimat & terjemahnya maksimal 300' using errcode = 'NL422';
  end if;

  if exists (
    select 1 from public.vocabularies v
    where v.language_id = s.language_id
      and lower(v.word) = lower(v_word)
      and lower(v.meaning_id) = lower(v_meaning)
  ) then
    raise exception 'Kata "%" dengan arti yang sama sudah ada di kamus', v_word using errcode = 'NL422';
  end if;

  insert into public.vocabularies (
    language_id, word, meaning_id, audio_url, category, source, contributed_by,
    speech_level, example_sentence, example_meaning
  )
  values (
    s.language_id, v_word, v_meaning, s.audio_url, 'kontribusi', 'kontribusi', s.user_id,
    v_speech_level, v_example, v_example_meaning
  )
  returning id into v_vocab_id;

  v_edited := v_word <> s.word or v_meaning <> s.meaning_id;

  update public.vocab_submissions
     set status = 'approved',
         word = v_word,
         meaning_id = v_meaning,
         original = case when v_edited then jsonb_build_object('word', s.word, 'meaning_id', s.meaning_id) end,
         review_note = v_note,
         reviewed_by = v_user,
         reviewed_at = now(),
         vocabulary_id = v_vocab_id
   where id = s.id;

  -- XP kontributor. XP per bahasa hanya ditambah bila user memang mengikuti
  -- bahasa itu (jangan diam-diam menambah bahasa yang diikuti).
  update public.profiles set xp_total = xp_total + v_xp where id = s.user_id;
  update public.user_languages
     set xp = xp + v_xp
   where user_id = s.user_id and language_id = s.language_id;
  insert into public.xp_logs (user_id, amount, source, source_id)
  values (s.user_id, v_xp, 'contribution', s.id::text);
  perform public.award_achievements(s.user_id);

  perform public.log_moderation(
    'submission_approved', s.language_id, 'submission', s.id::text,
    jsonb_build_object('word', v_word, 'vocabulary_id', v_vocab_id, 'edited', v_edited, 'note', v_note)
  );

  return jsonb_build_object('status', 'approved', 'vocabulary_id', v_vocab_id, 'xp_awarded', v_xp);
end;
$$;

-- ---------------------------------------------------------------------
-- RPC: get_submission_queue
-- Antrean usulan di bahasa yang dimoderasi, lengkap dengan nama & rekam
-- jejak pengusul, peninjau, kandidat duplikat (kata sama di kamus), dan
-- total_count untuk paginasi. Menunggu: tertua dulu; lainnya: terbaru dulu.
-- ---------------------------------------------------------------------
create or replace function public.get_submission_queue(
  p_status public.submission_status default 'pending',
  p_language_id bigint default null,
  p_limit integer default 20,
  p_offset integer default 0
)
returns table (
  id bigint,
  language_id bigint,
  language_name text,
  language_code text,
  word text,
  meaning_id text,
  audio_url text,
  status public.submission_status,
  created_at timestamptz,
  reviewed_at timestamptz,
  reject_reason public.reject_reason,
  review_note text,
  original jsonb,
  vocabulary_id bigint,
  submitter_id uuid,
  submitter_username text,
  submitter_approved bigint,
  submitter_reviewed bigint,
  reviewer_username text,
  is_own boolean,
  duplicates jsonb,
  total_count bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  with page as (
    select s.*, count(*) over () as total
    from public.vocab_submissions s
    where s.status = p_status
      and s.language_id in (select public.moderated_language_ids())
      and (p_language_id is null or s.language_id = p_language_id)
    order by
      case when p_status = 'pending' then s.created_at end asc,
      s.reviewed_at desc nulls last,
      s.created_at desc
    limit least(greatest(coalesce(p_limit, 20), 1), 50)
    offset greatest(coalesce(p_offset, 0), 0)
  )
  select
    pg.id,
    pg.language_id,
    l.name,
    l.code,
    pg.word,
    pg.meaning_id,
    pg.audio_url,
    pg.status,
    pg.created_at,
    pg.reviewed_at,
    pg.reject_reason,
    pg.review_note,
    pg.original,
    pg.vocabulary_id,
    pg.user_id,
    sub.username,
    stats.approved,
    stats.reviewed,
    rev.username,
    pg.user_id = (select auth.uid()),
    case when pg.status = 'pending' then coalesce(dup.items, '[]'::jsonb) else '[]'::jsonb end,
    pg.total
  from page pg
  join public.languages l on l.id = pg.language_id
  left join public.profiles sub on sub.id = pg.user_id
  left join public.profiles rev on rev.id = pg.reviewed_by
  left join lateral (
    select
      count(*) filter (where x.status = 'approved') as approved,
      count(*) filter (where x.status <> 'pending') as reviewed
    from public.vocab_submissions x
    where x.user_id = pg.user_id
  ) stats on true
  left join lateral (
    select jsonb_agg(jsonb_build_object('id', d.id, 'word', d.word, 'meaning_id', d.meaning_id)) as items
    from (
      select v.id, v.word, v.meaning_id
      from public.vocabularies v
      where v.language_id = pg.language_id and lower(v.word) = lower(pg.word)
      order by v.id
      limit 3
    ) d
  ) dup on true
  order by
    case when p_status = 'pending' then pg.created_at end asc,
    pg.reviewed_at desc nulls last,
    pg.created_at desc;
$$;

-- ---------------------------------------------------------------------
-- RPC: set_moderator_languages (khusus admin)
-- Mengganti daftar bahasa seorang moderator. Array kosong = cabut
-- (role kembali 'user'). Admin lain tidak bisa diubah lewat fungsi ini.
-- ---------------------------------------------------------------------
create or replace function public.set_moderator_languages(p_user uuid, p_language_ids bigint[])
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_admin uuid := (select auth.uid());
  v_role public.user_role;
  v_ids bigint[];
  v_added bigint[];
  v_removed bigint[];
  v_new_role public.user_role;
begin
  if v_admin is null or not public.is_admin() then
    raise exception 'Khusus admin' using errcode = '42501';
  end if;

  select role into v_role from public.profiles where id = p_user for update;
  if not found then
    raise exception 'Pengguna tidak ditemukan' using errcode = 'P0002';
  end if;
  if v_role = 'admin' then
    raise exception 'Admin sudah bisa memoderasi semua bahasa' using errcode = 'NL422';
  end if;

  select coalesce(array_agg(distinct i order by i), '{}') into v_ids
  from unnest(coalesce(p_language_ids, '{}')) as i;

  if exists (select 1 from unnest(v_ids) as i where not exists (select 1 from public.languages l where l.id = i)) then
    raise exception 'Ada bahasa yang tidak dikenal' using errcode = 'NL422';
  end if;

  with del as (
    delete from public.moderator_languages
    where user_id = p_user and not (language_id = any (v_ids))
    returning language_id
  )
  select coalesce(array_agg(language_id order by language_id), '{}') into v_removed from del;

  with ins as (
    insert into public.moderator_languages (user_id, language_id, assigned_by)
    select p_user, i, v_admin from unnest(v_ids) as i
    on conflict do nothing
    returning language_id
  )
  select coalesce(array_agg(language_id order by language_id), '{}') into v_added from ins;

  v_new_role := case when cardinality(v_ids) > 0 then 'moderator' else 'user' end;
  update public.profiles set role = v_new_role where id = p_user;

  if cardinality(v_added) > 0 then
    perform public.log_moderation('moderator_assigned', null, 'moderator', p_user::text, jsonb_build_object('language_ids', to_jsonb(v_added)));
  end if;
  if cardinality(v_removed) > 0 then
    perform public.log_moderation('moderator_removed', null, 'moderator', p_user::text, jsonb_build_object('language_ids', to_jsonb(v_removed)));
  end if;

  return jsonb_build_object('role', v_new_role, 'language_ids', to_jsonb(v_ids));
end;
$$;

-- ---------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------
alter table public.moderator_languages enable row level security;
alter table public.moderation_log enable row level security;

create policy "Lihat penugasan sendiri atau sebagai admin" on public.moderator_languages
  for select to authenticated
  using (user_id = (select auth.uid()) or (select public.is_admin()));

create policy "Lihat log bahasa yang dimoderasi" on public.moderation_log
  for select to authenticated
  using (
    language_id in (select public.moderated_language_ids())
    or (language_id is null and (select public.is_admin()))
  );

-- Usulan: moderator hanya melihat bahasa yang ia pegang.
drop policy "Lihat usulan sendiri atau sebagai moderator" on public.vocab_submissions;
create policy "Lihat usulan sendiri atau bahasa yang dimoderasi" on public.vocab_submissions
  for select to authenticated
  using ((select auth.uid()) = user_id or language_id in (select public.moderated_language_ids()));

-- Keputusan tidak lagi lewat UPDATE langsung, tetapi review_submission().
drop policy "Moderator meninjau usulan" on public.vocab_submissions;

create policy "Batalkan usulan sendiri yang menunggu" on public.vocab_submissions
  for delete to authenticated
  using ((select auth.uid()) = user_id and status = 'pending');

-- ---------------------------------------------------------------------
-- Hak akses kolom & fungsi
-- ---------------------------------------------------------------------
revoke insert, update, delete on public.moderator_languages, public.moderation_log from anon, authenticated;

-- Usulan: client hanya mengisi kolom usulan; kolom tinjauan diisi RPC.
revoke insert, update, delete on public.vocab_submissions from anon, authenticated;
grant insert (user_id, language_id, word, meaning_id, audio_url, status) on public.vocab_submissions to authenticated;
grant delete on public.vocab_submissions to authenticated;

-- Helper dipakai di policy → perlu execute untuk authenticated.
revoke execute on function public.is_admin() from public, anon;
revoke execute on function public.moderated_language_ids() from public, anon;
revoke execute on function public.can_moderate(bigint) from public, anon;
grant execute on function public.is_admin() to authenticated;
grant execute on function public.moderated_language_ids() to authenticated;
grant execute on function public.can_moderate(bigint) to authenticated;

-- Internal.
revoke execute on function public.log_moderation(public.moderation_action, bigint, text, text, jsonb) from public, anon, authenticated;
revoke execute on function public.limit_pending_submissions() from public, anon, authenticated;

-- RPC untuk client.
revoke execute on function public.review_submission(bigint, public.submission_status, public.reject_reason, text, jsonb) from public, anon;
revoke execute on function public.get_submission_queue(public.submission_status, bigint, integer, integer) from public, anon;
revoke execute on function public.set_moderator_languages(uuid, bigint[]) from public, anon;
grant execute on function public.review_submission(bigint, public.submission_status, public.reject_reason, text, jsonb) to authenticated;
grant execute on function public.get_submission_queue(public.submission_status, bigint, integer, integer) to authenticated;
grant execute on function public.set_moderator_languages(uuid, bigint[]) to authenticated;

commit;
