-- Usulan yang disetujui otomatis masuk kamus (vocabularies) dan dicek lencananya.
create or replace function public.on_submission_reviewed()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.status = 'approved' and old.status is distinct from 'approved' then
    insert into public.vocabularies (language_id, word, meaning_id, audio_url, category)
    values (new.language_id, new.word, new.meaning_id, new.audio_url, 'kontribusi');
    perform public.award_achievements(new.user_id);
  end if;
  return new;
end;
$$;

create trigger vocab_submission_reviewed
  after update of status on public.vocab_submissions
  for each row execute function public.on_submission_reviewed();

