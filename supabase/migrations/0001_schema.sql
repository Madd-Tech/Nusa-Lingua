-- ---------------------------------------------------------------------
-- View: weekly_leaderboard (minggu Senin–Minggu, WIB)
-- Dijalankan sebagai pemilik view (bukan security_invoker) agar bisa
-- menjumlahkan xp_logs semua user; hanya kolom publik yang diekspos.
-- ---------------------------------------------------------------------
create view public.weekly_leaderboard as
select
  p.id as user_id,
  p.username,
  p.avatar_url,
  p.home_region_id,
  sum(x.amount)::integer as weekly_xp
from public.xp_logs x
join public.profiles p on p.id = x.user_id
where x.created_at >= (date_trunc('week', now() at time zone 'Asia/Jakarta') at time zone 'Asia/Jakarta')
  and p.username is not null
group by p.id, p.username, p.avatar_url, p.home_region_id;

