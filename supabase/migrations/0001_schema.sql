-- true jika user saat ini moderator/admin (dipakai di policy).
create or replace function public.is_moderator()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role in ('moderator', 'admin')
  );
$$;

-- Profil dibuat otomatis saat sign up (full_name & avatar_url dari user_metadata).
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, avatar_url)
  values (
    new.id,
    left(coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name'), 80),
    coalesce(new.raw_user_meta_data ->> 'avatar_url', new.raw_user_meta_data ->> 'picture')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Berikan lencana yang syaratnya sudah terpenuhi (dipanggil dari RPC & trigger).
create or replace function public.award_achievements(p_user uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  s record;
begin
  select
    (select count(*) from public.user_lesson_progress where user_id = p_user and status = 'completed') as lessons_completed,
    (select count(*) from public.user_lesson_progress where user_id = p_user and stars = 3) as perfect_lesson,
    (select coalesce(current_streak, 0) from public.profiles where id = p_user) as streak,
    (select coalesce(xp_total, 0) from public.profiles where id = p_user) as xp_total,
    (select count(*) from public.user_article_reads where user_id = p_user) as articles_read,
    (select count(*) from public.vocab_submissions where user_id = p_user and status = 'approved') as contributions_approved
  into s;

  insert into public.user_achievements (user_id, achievement_id)
  select p_user, a.id
  from public.achievements a
  where (a.condition ->> 'value') ~ '^\d+$'
    and case a.condition ->> 'type'
      when 'lessons_completed' then s.lessons_completed >= (a.condition ->> 'value')::int
      when 'perfect_lesson' then s.perfect_lesson >= (a.condition ->> 'value')::int
      when 'streak' then s.streak >= (a.condition ->> 'value')::int
      when 'xp_total' then s.xp_total >= (a.condition ->> 'value')::int
      when 'articles_read' then s.articles_read >= (a.condition ->> 'value')::int
      when 'contributions_approved' then s.contributions_approved >= (a.condition ->> 'value')::int
      else false
    end
  on conflict (user_id, achievement_id) do nothing;
end;
$$;

-- ---------------------------------------------------------------------
-- RPC: complete_lesson
-- Mengurus progres lesson, XP (profil + per bahasa), xp_logs, streak (WIB), lencana.
-- Mengembalikan {"xp_gained": int, "stars": int, "streak": int}.
-- ---------------------------------------------------------------------
create or replace function public.complete_lesson(p_lesson_id bigint, p_score integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_score integer := least(100, greatest(0, coalesce(p_score, 0)));
  v_today date := (now() at time zone 'Asia/Jakarta')::date;
  v_xp_reward integer;
  v_language_id bigint;
  v_was_completed boolean;
  v_stars integer;
  v_xp integer;
  v_last date;
  v_streak integer;
begin
  if v_user is null then
    raise exception 'Harus login untuk menyelesaikan lesson' using errcode = '28000';
  end if;

  select l.xp_reward, u.language_id
    into v_xp_reward, v_language_id
  from public.lessons l
  join public.units u on u.id = l.unit_id
  where l.id = p_lesson_id;

  if not found then
    raise exception 'Lesson % tidak ditemukan', p_lesson_id using errcode = 'P0002';
  end if;

  -- Profil wajib ada (dibuat trigger saat sign up).
  select current_streak, last_active_date
    into v_streak, v_last
  from public.profiles
  where id = v_user
  for update;

  if not found then
    raise exception 'Profil tidak ditemukan' using errcode = 'P0002';
  end if;

  select exists (
    select 1 from public.user_lesson_progress
    where user_id = v_user and lesson_id = p_lesson_id and status = 'completed'
  ) into v_was_completed;

  v_stars := case when v_score >= 90 then 3 when v_score >= 70 then 2 else 1 end;
  -- Penyelesaian pertama: XP penuh × skor. Mengulang: setengahnya.
  v_xp := greatest(
    1,
    round(v_xp_reward * v_score / case when v_was_completed then 200.0 else 100.0 end)::integer
  );

  insert into public.user_lesson_progress (user_id, lesson_id, status, best_score, stars, attempts, completed_at)
  values (v_user, p_lesson_id, 'completed', v_score, v_stars, 1, now())
  on conflict (user_id, lesson_id) do update
    set status = 'completed',
        best_score = greatest(public.user_lesson_progress.best_score, excluded.best_score),
        stars = greatest(public.user_lesson_progress.stars, excluded.stars),
        attempts = public.user_lesson_progress.attempts + 1,
        completed_at = coalesce(public.user_lesson_progress.completed_at, now());

  -- Streak berbasis tanggal WIB.
  v_streak := case
    when v_last = v_today then greatest(coalesce(v_streak, 0), 1)
    when v_last = v_today - 1 then coalesce(v_streak, 0) + 1
    else 1
  end;

  update public.profiles
     set xp_total = xp_total + v_xp,
         current_streak = v_streak,
         longest_streak = greatest(longest_streak, v_streak),
         last_active_date = v_today
   where id = v_user;

  insert into public.user_languages (user_id, language_id, xp)
  values (v_user, v_language_id, v_xp)
  on conflict (user_id, language_id) do update
    set xp = public.user_languages.xp + excluded.xp;

  insert into public.xp_logs (user_id, amount, source, source_id)
  values (v_user, v_xp, 'lesson', p_lesson_id::text);

  perform public.award_achievements(v_user);

  return jsonb_build_object('xp_gained', v_xp, 'stars', v_stars, 'streak', v_streak);
end;
$$;

